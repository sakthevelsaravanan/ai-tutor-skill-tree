-- PostgreSQL 18. Applied transactionally by scripts/bootstrap_postgres.py.
CREATE TABLE users (
 user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(100) NOT NULL,
 email varchar(255) NOT NULL UNIQUE,
 password_hash text NOT NULL,
 role text NOT NULL CHECK (role IN ('student','instructor','admin')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower ON users(lower(email));
CREATE TABLE subjects (
 subject_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject_key varchar(50) NOT NULL UNIQUE,
 subject_name varchar(100) NOT NULL,
 description text,
 is_indexed boolean NOT NULL DEFAULT false,
 created_by integer REFERENCES users ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE textbooks (
 textbook_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject_id integer NOT NULL REFERENCES subjects ON DELETE CASCADE,
 uploaded_by integer REFERENCES users ON DELETE SET NULL,
 file_name varchar(255) NOT NULL,
 chroma_collection_name text NOT NULL,
 chunk_count integer NOT NULL DEFAULT 0 CHECK (chunk_count >= 0),
 uploaded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(subject_id,file_name)
);
CREATE TABLE topics (
 topic_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject_id integer NOT NULL REFERENCES subjects ON DELETE CASCADE,
 topic_name varchar(100) NOT NULL,
 difficulty_level smallint NOT NULL CHECK (difficulty_level BETWEEN 1 AND 3),
 visual_type text NOT NULL DEFAULT 'p5js' CHECK (visual_type IN ('iframe','p5js')),
 embed_url text,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(subject_id,topic_name)
);
CREATE TABLE topic_prerequisites (
 topic_id integer NOT NULL REFERENCES topics ON DELETE CASCADE,
 prereq_topic_id integer NOT NULL REFERENCES topics ON DELETE CASCADE,
 importance_weight smallint NOT NULL DEFAULT 3 CHECK (importance_weight BETWEEN 1 AND 5),
 PRIMARY KEY(topic_id,prereq_topic_id),
 CHECK(topic_id <> prereq_topic_id)
);
CREATE INDEX prereq_parent ON topic_prerequisites(prereq_topic_id);
CREATE TABLE learning_sessions (
 session_id uuid PRIMARY KEY,
 user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
 subject_id integer NOT NULL REFERENCES subjects ON DELETE CASCADE,
 current_topic_id integer REFERENCES topics ON DELETE SET NULL,
 current_stage text NOT NULL DEFAULT 'topic' CHECK(current_stage IN ('topic','explore','quiz','check','clarify')),
 quiz_difficulty smallint NOT NULL DEFAULT 1 CHECK(quiz_difficulty BETWEEN 1 AND 3),
 confused_count integer NOT NULL DEFAULT 0 CHECK(confused_count >= 0),
 started_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_session_user ON learning_sessions(user_id,updated_at DESC);
CREATE TABLE conversation_logs (
 log_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id uuid NOT NULL REFERENCES learning_sessions ON DELETE CASCADE,
 topic_id integer REFERENCES topics ON DELETE SET NULL,
 role text NOT NULL CHECK(role IN ('user','assistant','system')),
 stage text NOT NULL CHECK(stage IN ('topic','explore','quiz','check','clarify')),
 content text NOT NULL CHECK(length(trim(content)) > 0),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX conversation_session ON conversation_logs(session_id,log_id);
CREATE TABLE quiz_attempts (
 attempt_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id uuid NOT NULL REFERENCES learning_sessions ON DELETE CASCADE,
 user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
 topic_id integer NOT NULL REFERENCES topics ON DELETE CASCADE,
 difficulty_level smallint NOT NULL CHECK(difficulty_level BETWEEN 1 AND 3),
 mcq_score smallint CHECK(mcq_score BETWEEN 0 AND 3),
 check_score smallint CHECK(check_score BETWEEN 1 AND 5),
 verdict text NOT NULL CHECK(verdict IN ('UNDERSTOOD','PARTIAL','CONFUSED')),
 attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attempt_user_topic ON quiz_attempts(user_id,topic_id);
CREATE TABLE student_topic_mastery (
 user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
 topic_id integer NOT NULL REFERENCES topics ON DELETE CASCADE,
 mastery_status text NOT NULL DEFAULT 'UNTOUCHED' CHECK(mastery_status IN ('UNTOUCHED','IN_PROGRESS','NEEDS_PREREQ_REVIEW','MASTERED')),
 best_mcq_score smallint CHECK(best_mcq_score BETWEEN 0 AND 3),
 latest_check_score smallint CHECK(latest_check_score BETWEEN 1 AND 5),
 total_attempts integer NOT NULL DEFAULT 0 CHECK(total_attempts >= 0),
 last_updated timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(user_id,topic_id)
);

CREATE FUNCTION validate_prerequisite() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE subject integer;
BEGIN
 SELECT subject_id INTO subject FROM topics WHERE topic_id=NEW.topic_id;
 -- Serialize graph writes within a subject to avoid concurrent cycle creation.
 PERFORM pg_advisory_xact_lock(91001, subject);
 IF subject IS DISTINCT FROM (SELECT subject_id FROM topics WHERE topic_id=NEW.prereq_topic_id) THEN
  RAISE EXCEPTION 'Prerequisites must belong to the same subject';
 END IF;
 IF NEW.topic_id=NEW.prereq_topic_id OR EXISTS (
  WITH RECURSIVE ancestors(id) AS (
   SELECT NEW.prereq_topic_id UNION
   SELECT p.prereq_topic_id FROM topic_prerequisites p JOIN ancestors a ON p.topic_id=a.id
   WHERE TG_OP <> 'UPDATE' OR (p.topic_id,p.prereq_topic_id) <> (OLD.topic_id,OLD.prereq_topic_id)
  ) SELECT 1 FROM ancestors WHERE id=NEW.topic_id
 ) THEN RAISE EXCEPTION 'Prerequisite edge would create a cycle'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER prerequisite_integrity BEFORE INSERT OR UPDATE ON topic_prerequisites
 FOR EACH ROW EXECUTE FUNCTION validate_prerequisite();

CREATE FUNCTION validate_session() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.current_topic_id IS NOT NULL AND NEW.subject_id IS DISTINCT FROM
  (SELECT subject_id FROM topics WHERE topic_id=NEW.current_topic_id) THEN
  RAISE EXCEPTION 'Session topic must belong to its subject';
 END IF;
 NEW.updated_at=now();
 RETURN NEW;
END $$;
CREATE TRIGGER session_integrity BEFORE INSERT OR UPDATE ON learning_sessions
 FOR EACH ROW EXECUTE FUNCTION validate_session();

CREATE FUNCTION validate_attempt() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE session learning_sessions;
BEGIN
 SELECT * INTO STRICT session FROM learning_sessions WHERE session_id=NEW.session_id FOR UPDATE;
 IF NEW.user_id <> session.user_id OR session.subject_id IS DISTINCT FROM
  (SELECT subject_id FROM topics WHERE topic_id=NEW.topic_id) THEN
  RAISE EXCEPTION 'Quiz ownership or topic subject mismatch';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attempt_integrity BEFORE INSERT OR UPDATE ON quiz_attempts
 FOR EACH ROW EXECUTE FUNCTION validate_attempt();

CREATE FUNCTION update_quiz_mastery() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE status text;
BEGIN
 status=CASE WHEN NEW.verdict='CONFUSED' OR (NEW.mcq_score<=1 AND NEW.check_score<=2)
  THEN 'NEEDS_PREREQ_REVIEW'
  WHEN NEW.verdict='UNDERSTOOD' AND NEW.mcq_score=3 AND NEW.check_score>=4 THEN 'MASTERED'
  ELSE 'IN_PROGRESS' END;
 INSERT INTO student_topic_mastery(user_id,topic_id,mastery_status,best_mcq_score,latest_check_score,total_attempts)
 VALUES(NEW.user_id,NEW.topic_id,status,NEW.mcq_score,NEW.check_score,1)
 ON CONFLICT(user_id,topic_id) DO UPDATE SET mastery_status=EXCLUDED.mastery_status,
 best_mcq_score=GREATEST(student_topic_mastery.best_mcq_score,EXCLUDED.best_mcq_score),
 latest_check_score=COALESCE(EXCLUDED.latest_check_score,student_topic_mastery.latest_check_score),
 total_attempts=student_topic_mastery.total_attempts+1,last_updated=now();
 RETURN NEW;
END $$;
CREATE TRIGGER trg_after_quiz_attempt_mastery AFTER INSERT ON quiz_attempts
 FOR EACH ROW EXECUTE FUNCTION update_quiz_mastery();

CREATE FUNCTION flag_confusion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.confused_count>=3 AND OLD.confused_count<3 AND NEW.current_topic_id IS NOT NULL THEN
  INSERT INTO student_topic_mastery(user_id,topic_id,mastery_status)
  VALUES(NEW.user_id,NEW.current_topic_id,'NEEDS_PREREQ_REVIEW')
  ON CONFLICT(user_id,topic_id) DO UPDATE SET mastery_status='NEEDS_PREREQ_REVIEW',last_updated=now();
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_after_session_confused_threshold AFTER UPDATE ON learning_sessions
 FOR EACH ROW EXECUTE FUNCTION flag_confusion();

CREATE FUNCTION fn_calculate_subject_mastery(p_user integer,p_subject integer)
 RETURNS numeric LANGUAGE sql STABLE AS $$
 SELECT COALESCE(round(100.0*count(*) FILTER(WHERE m.mastery_status='MASTERED')/NULLIF(count(*),0),2),0)
 FROM topics t LEFT JOIN student_topic_mastery m ON m.topic_id=t.topic_id AND m.user_id=p_user
 WHERE t.subject_id=p_subject;
$$;

CREATE FUNCTION recommend_next_topic(p_user integer,p_subject integer)
 RETURNS TABLE(recommended_topic_id integer,recommendation_reason text) LANGUAGE sql STABLE AS $$
 WITH candidates AS (
 SELECT p.prereq_topic_id AS id,1 AS priority,p.importance_weight AS weight,'Remediation: review an unmet prerequisite.' AS reason
 FROM student_topic_mastery m JOIN topics t USING(topic_id) JOIN topic_prerequisites p USING(topic_id)
 LEFT JOIN student_topic_mastery pm ON pm.user_id=p_user AND pm.topic_id=p.prereq_topic_id
 WHERE m.user_id=p_user AND t.subject_id=p_subject AND m.mastery_status='NEEDS_PREREQ_REVIEW'
 AND COALESCE(pm.mastery_status,'UNTOUCHED')<>'MASTERED'
 UNION ALL
 SELECT t.topic_id,2,0,'Continuity: resume an in-progress topic.' FROM topics t
 JOIN student_topic_mastery m USING(topic_id) WHERE t.subject_id=p_subject AND m.user_id=p_user AND m.mastery_status='IN_PROGRESS'
 UNION ALL
 SELECT t.topic_id,3,-t.difficulty_level,'Progression: prerequisites are fulfilled.' FROM topics t
 LEFT JOIN student_topic_mastery m ON m.topic_id=t.topic_id AND m.user_id=p_user
 WHERE t.subject_id=p_subject AND COALESCE(m.mastery_status,'UNTOUCHED') IN ('UNTOUCHED','NEEDS_PREREQ_REVIEW')
 AND NOT EXISTS(SELECT 1 FROM topic_prerequisites p LEFT JOIN student_topic_mastery pm
 ON pm.topic_id=p.prereq_topic_id AND pm.user_id=p_user WHERE p.topic_id=t.topic_id AND COALESCE(pm.mastery_status,'UNTOUCHED')<>'MASTERED')
 ) SELECT id,reason FROM candidates ORDER BY priority,weight DESC,id LIMIT 1;
$$;

CREATE FUNCTION record_quiz_and_advance_stage(p_session uuid,p_topic integer,p_mcq integer,p_check integer,p_verdict text)
 RETURNS integer LANGUAGE plpgsql AS $$
DECLARE s learning_sessions; result integer;
BEGIN
 SELECT * INTO STRICT s FROM learning_sessions WHERE session_id=p_session FOR UPDATE;
 INSERT INTO quiz_attempts(session_id,user_id,topic_id,difficulty_level,mcq_score,check_score,verdict)
 VALUES(p_session,s.user_id,p_topic,s.quiz_difficulty,p_mcq,p_check,p_verdict) RETURNING attempt_id INTO result;
 UPDATE learning_sessions SET current_topic_id=p_topic,
 current_stage=CASE p_verdict WHEN 'CONFUSED' THEN 'clarify' WHEN 'UNDERSTOOD' THEN 'explore' ELSE 'check' END,
 confused_count=CASE p_verdict WHEN 'CONFUSED' THEN CASE WHEN current_topic_id=p_topic THEN confused_count+1 ELSE 1 END
 WHEN 'UNDERSTOOD' THEN 0 ELSE CASE WHEN current_topic_id=p_topic THEN confused_count ELSE 0 END END
 WHERE session_id=p_session;
 RETURN result;
END $$;

CREATE VIEW vw_student_curriculum AS
 SELECT s.subject_id,s.subject_name,t.topic_id,t.topic_name,t.difficulty_level,t.visual_type,t.embed_url
 FROM subjects s JOIN topics t USING(subject_id) WHERE s.is_indexed;
CREATE VIEW vw_available_subjects AS
 SELECT s.*, (SELECT count(*) FROM topics t WHERE t.subject_id=s.subject_id) AS total_topics,
 (SELECT count(*) FROM textbooks b WHERE b.subject_id=s.subject_id) AS total_textbooks FROM subjects s;
CREATE VIEW vw_topic_prerequisite_graph AS
 SELECT p.*,t.topic_name,r.topic_name AS prereq_topic_name FROM topic_prerequisites p
 JOIN topics t ON t.topic_id=p.topic_id JOIN topics r ON r.topic_id=p.prereq_topic_id;
